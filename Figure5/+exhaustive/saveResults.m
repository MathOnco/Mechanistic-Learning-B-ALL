function bestFeatures = saveResults(R, C, cfg)
%SAVERESULTS Write held-out summaries, stability tables, MAT, and figures.

stem = lower(char(R.outcome + "__" + R.view + "__" + R.model));
K = R.meta.K;
p = R.meta.p;

bestByK = table();
for k = 1:K
    M = exhaustive.metrics(C.y, R.meanOOFScores(:, k));
    row = table(R.view, R.outcome, R.model, R.lambda, k, nchoosek(p, k), ...
        M.n, M.nPositive, M.nNegative, M.accuracy, M.balancedAccuracy, ...
        M.sensitivity, M.specificity, M.auc, ...
        'VariableNames', {'view','outcome','model','fixedLambda','k', ...
        'numberOfCandidateSubsets','n','nPositive','nNegative','accuracy', ...
        'balancedAccuracy','sensitivity','specificity','auc'});
    bestByK = [bestByK; row]; %#ok<AGROW>
end
writetable(bestByK, fullfile(cfg.outputDir, [stem '__best_by_k.csv']));

outerDetails = buildOuterDetails(R, C);
writetable(outerDetails, fullfile(cfg.outputDir, ...
    [stem '__outer_fold_details.csv']));

bestFeatures = buildBestFeatureReport(R, C.featureNames, bestByK, outerDetails);
writetable(bestFeatures, fullfile(cfg.outputDir, ...
    [stem '__best_features_and_accuracies.csv']));

subsetStability = buildSubsetStability(R, C.featureNames);
writetable(subsetStability, fullfile(cfg.outputDir, ...
    [stem '__subset_stability.csv']));

featureStability = buildFeatureStability(R, C.featureNames);
writetable(featureStability, fullfile(cfg.outputDir, ...
    [stem '__feature_stability.csv']));

oof = table(C.originalIndex, C.patientID, C.sampleID, C.y, ...
    'VariableNames', {'originalIndex','patientID','sampleID','outcome'});
for k = 1:K
    oof.(sprintf('score_k%02d', k)) = R.meanOOFScores(:, k);
end
writetable(oof, fullfile(cfg.outputDir, [stem '__oof_scores.csv']));

save(fullfile(cfg.outputDir, [stem '__result.mat']), 'R', 'C', 'cfg', '-v7.3');
makeFigure(bestByK, R, cfg, stem);
fprintf('  Saved final outputs for %s\n', stem);
end

function T = buildBestFeatureReport(R, featureNames, bestByK, outerDetails)
% One reportable row per k without an additional full-cohort exhaustive pass.
T = table();
denominator = R.meta.nRepeats * R.meta.outerFolds;
for k = 1:R.meta.K
    rows = outerDetails(outerDetails.k == k, :);
    masks = unique(rows.selectedMask);
    candidate = table();
    for u = 1:numel(masks)
        selected = rows.selectedMask == masks(u);
        candidate(u, :) = table(masks(u), sum(selected), ...
            mean(rows.innerSelectionValue(selected)), ...
            mean(rows.innerAccuracy(selected)), ...
            mean(rows.testAccuracy(selected)), ...
            'VariableNames', {'mask','count','meanSelectionValue', ...
            'meanInnerAccuracy','meanOuterFoldAccuracy'});
    end
    % Prefer the most frequently selected exact subset. Break frequency ties
    % by inner selection score, then inner accuracy, then numeric mask.
    candidate = sortrows(candidate, ...
        {'count','meanSelectionValue','meanInnerAccuracy','mask'}, ...
        {'descend','descend','descend','ascend'});
    winner = candidate(1, :);
    nested = bestByK(bestByK.k == k, :);

    labels = strings(height(candidate), 1);
    for u = 1:height(candidate)
        labels(u) = exhaustive.maskToString(uint16(candidate.mask(u)), featureNames) + ...
            " (" + string(candidate.count(u)) + "/" + string(denominator) + ")";
    end
    selectionSummary = strjoin(labels, '; ');
    winnerFeatures = exhaustive.maskToString(uint16(winner.mask), featureNames);

    row = table(R.view, R.outcome, R.model, R.lambda, k, nchoosek(R.meta.p, k), ...
        winner.mask, winnerFeatures, winner.count, winner.count / denominator, ...
        winner.meanSelectionValue, winner.meanInnerAccuracy, ...
        winner.meanOuterFoldAccuracy, nested.accuracy, ...
        nested.balancedAccuracy, nested.auc, selectionSummary, ...
        'VariableNames', {'view','outcome','model','fixedLambda','k', ...
        'numberOfCandidateSubsets','consensusMask','bestFeatures', ...
        'outerFitsSelectingConsensus','consensusSelectionFrequency', ...
        'meanInnerSelectionValueForConsensus','meanInnerAccuracyForConsensus', ...
        'meanHeldOutFoldAccuracyForConsensus','nestedHeldOutAccuracy', ...
        'nestedHeldOutBalancedAccuracy','nestedHeldOutAUC', ...
        'allOuterSelectedSubsets'});
    T = [T; row]; %#ok<AGROW>
end
end

function T = buildOuterDetails(R, C)
T = table();
for r = 1:R.meta.nRepeats
    for f = 1:R.meta.outerFolds
        te = R.outerFoldIndex(:, r) == f;
        for k = 1:R.meta.K
            selectedMask = R.selectedMasks(r, f, k);
            activeMask = R.activeMasks(r, f, k);
            M = exhaustive.metrics(C.y(te), R.oofScores(te, r, k));
            inner = squeeze(R.innerMetrics(r, f, k, :));
            row = table(R.view, R.outcome, R.model, R.lambda, r, f, k, ...
                double(selectedMask), ...
                exhaustive.maskToString(selectedMask, C.featureNames), ...
                double(activeMask), ...
                exhaustive.maskToString(activeMask, C.featureNames), ...
                R.innerSelectionValue(r, f, k), inner(1), inner(2), ...
                inner(3), inner(4), R.nCombinations(r, f, k), ...
                R.nFailed(r, f, k), R.elapsedSeconds(r, f, k), ...
                R.logLikelihood(r, f, k), R.df(r, f, k), ...
                R.bic(r, f, k), R.ebicGamma05(r, f, k), ...
                R.ebicGamma1(r, f, k), M.n, M.accuracy, ...
                M.balancedAccuracy, M.sensitivity, M.specificity, M.auc, ...
                'VariableNames', {'view','outcome','model','fixedLambda','repeat', ...
                'outerFold','k','selectedMask','selectedFeatures','activeMask', ...
                'activeFeatures','innerSelectionValue','innerAccuracy', ...
                'innerBalancedAccuracy','innerAUC','innerCombo', ...
                'numberOfCandidateSubsets','numberFailed','searchSeconds', ...
                'trainingLogLikelihood','effectiveDf','trainingBIC', ...
                'trainingEBICgamma05','trainingEBICgamma1','nTest', ...
                'testAccuracy','testBalancedAccuracy','testSensitivity', ...
                'testSpecificity','testAUC'});
            T = [T; row]; %#ok<AGROW>
        end
    end
end
end

function T = buildSubsetStability(R, featureNames)
T = table();
denominator = R.meta.nRepeats * R.meta.outerFolds;
for k = 1:R.meta.K
    masks = reshape(R.selectedMasks(:, :, k), [], 1);
    uniqueMasks = unique(masks);
    for u = 1:numel(uniqueMasks)
        count = sum(masks == uniqueMasks(u));
        row = table(R.view, R.outcome, R.model, R.lambda, k, ...
            double(uniqueMasks(u)), ...
            exhaustive.maskToString(uniqueMasks(u), featureNames), ...
            count, count / denominator, ...
            'VariableNames', {'view','outcome','model','fixedLambda','k', ...
            'selectedMask','selectedFeatures','count','proportion'});
        T = [T; row]; %#ok<AGROW>
    end
end
T = sortrows(T, {'k','count'}, {'ascend','descend'});
end

function T = buildFeatureStability(R, featureNames)
T = table();
denominator = R.meta.nRepeats * R.meta.outerFolds;
for k = 1:R.meta.K
    selected = reshape(R.selectedMasks(:, :, k), [], 1);
    active = reshape(R.activeMasks(:, :, k), [], 1);
    for j = 1:numel(featureNames)
        selectedCount = sum(bitget(selected, j) ~= 0);
        activeCount = sum(bitget(active, j) ~= 0);
        row = table(R.view, R.outcome, R.model, R.lambda, k, featureNames(j), ...
            selectedCount, selectedCount / denominator, activeCount, ...
            activeCount / denominator, ...
            'VariableNames', {'view','outcome','model','fixedLambda','k','feature', ...
            'candidateInclusionCount','candidateInclusionFrequency', ...
            'nonzeroCoefficientCount','nonzeroCoefficientFrequency'});
        T = [T; row]; %#ok<AGROW>
    end
end
end

function makeFigure(T, R, cfg, stem)
fig = figure('Visible', 'off', 'Color', 'w', 'Position', [100 100 850 520]);
plot(T.k, T.auc, '-o', 'LineWidth', 1.8, 'MarkerFaceColor', [0.15 0.45 0.75]);
hold on;
plot(T.k, T.balancedAccuracy, '-s', 'LineWidth', 1.8, ...
    'MarkerFaceColor', [0.85 0.40 0.15]);
hold off;
ylim([0 1]); xlim([0.5, R.meta.K + 0.5]); xticks(1:R.meta.K);
grid on; box off;
xlabel('Candidate subset size k');
ylabel('Held-out performance');
title(sprintf('%s | %s | %s | fixed \\lambda = %.4g', ...
    char(R.outcome), char(R.view), char(R.model), R.lambda), 'Interpreter', 'tex');
legend({'AUC','Balanced accuracy'}, 'Location', 'best');
exportgraphics(fig, fullfile(cfg.outputDir, ...
    [stem '__performance_by_k.png']), 'Resolution', 300);
close(fig);
end
