function lambda = lambdaFor(cfg, view, outcome, model)
%LAMBDAFOR Retrieve one endpoint/model-specific fixed mean lambda.

row = cfg.lambdaTable.view == lower(string(view)) & ...
    cfg.lambdaTable.outcome == string(outcome) & ...
    cfg.lambdaTable.model == lower(string(model));
if sum(row) ~= 1
    error('exhaustive:MissingLambda', ...
        'Expected one lambda for view=%s, outcome=%s, and model=%s; found %d.', ...
        view, outcome, model, sum(row));
end
lambda = cfg.lambdaTable.lambda(row);
end
